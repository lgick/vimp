// Кэш распределения очков одного среза рейтинга — то, из чего считается МЕСТО
// игрока, без похода в базу на каждого игрока.
//
// ***** ЗАЧЕМ *****
//
// Место — это «сколько игроков впереди меня», и считалось оно запросом на
// каждый вход участника: свёртка всего окна игры плюс join к users. Замер на
// 8 000 игроков в окне — 6 мс. На целевом масштабе (100 игр × 100 серверов ×
// 8 игроков, сессия ~10 минут) это ~1200 таких запросов в секунду, то есть
// семь ядер одной только этой строчки.
//
// При этом ответ на всех один и тот же. Распределение очков игры за окно
// стоит ровно столько же, сколько ОДИН такой запрос (замер: 5.4 мс), и
// отвечает всем игрокам на весь TTL:
//
//   было: 1200 запросов/с × 6 мс          ≈ 7 ядер;
//   стало: 10 запросов/с × 5.4 мс         ≈ 5 % ядра,
//          плюс точечный поиск своего значения по первичному ключу (0.17 мс).
//
// ***** ЧТО ХРАНИТСЯ *****
//
// Не список игроков, а лестница РАЗЛИЧНЫХ значений по убыванию и число
// игроков «на этой ступени и выше». Место игрока — бинарный поиск по ней:
//
//   place(S) = 1 + (сколько игроков строго выше S).
//
// Это в точности `RANK() OVER (ORDER BY rank DESC)` из getLeaderboard, то
// есть competition ranking: разделившие значение делят место, а следующее
// отличное перескакивает на размер группы. Плашка позиции и список рядом с
// ней обязаны совпадать, поэтому определение здесь ровно то же.
//
// Лестница различных значений, а не всех игроков: игроков в месячном окне
// могут быть сотни тысяч, а различных сумм очков — заметно меньше, и память
// кэша перестаёт зависеть от размера игры линейно.
//
// ***** ГРАНИЦЫ *****
//
// Лестница обрезается на `maxSteps` ступенях. Для среза, который в них не
// уместился, глубокий хвост (игрок ниже последней ступени) уходит на точный
// запрос — редкий случай, оплаченный тем, что все остальные его не делают.
// Так кэш не растёт неограниченно на игре с миллионом игроков за всё время.
//
// ***** СВЕЖЕСТЬ *****
//
// Своё значение читается ЖИВЫМ (точечный поиск), устаревать может только
// лестница, и не дольше TTL. Ошибиться она может лишь в одну сторону:
// `best` и `points` только растут, поэтому старая лестница может насчитать
// впереди лишних, но не может потерять уже обогнавших.
export default class RankDistribution {
  // loader(gameId, period, maxSteps) -> { steps: [{ score, atOrAbove }], total }
  constructor(loader, { ttlMs = 30000, maxSteps = 50000, now = () => Date.now() } = {}) {
    this._load = loader;
    this._ttlMs = ttlMs;
    this._maxSteps = maxSteps;
    this._now = now;
    this._cache = new Map(); // `${game}:${period}` -> { at, value, pending }
  }

  // Лестница среза. Запрос на холодный ключ ОДИН: промис кладётся в кэш до
  // ожидания, и наплыв входов в комнату получает его же, а не по запросу на
  // каждого — иначе первая же секунда после протухания стоила бы столько,
  // сколько весь кэш и экономит
  async get(gameId, period) {
    const key = `${gameId}:${period}`;
    const now = this._now();
    const hit = this._cache.get(key);

    if (hit && now - hit.at < this._ttlMs) {
      return hit.pending ?? hit.value;
    }

    const pending = this._load(gameId, period, this._maxSteps)
      .then(value => {
        this._cache.set(key, { at: this._now(), value, pending: null });

        return value;
      })
      .catch(err => {
        // отказ не залипает на весь TTL: следующий вызов попробует снова, а
        // этот отвечает «лестницы нет» — вызывающий уходит на точный запрос
        this._cache.delete(key);
        console.warn(`[rank] distribution failed for ${key}:`, err.message);

        return null;
      });

    this._cache.set(key, { at: now, value: null, pending });

    return pending;
  }

  // Место игрока со значением `score`, или null, если по этой лестнице
  // ответить точно нельзя (игрок ниже её обрезанного хвоста) — тогда
  // вызывающий считает точным запросом
  static placementOf(distribution, score) {
    if (!distribution || score <= 0) {
      return null;
    }

    const { steps, complete } = distribution;

    // впереди никого: значение не ниже верхней ступени
    if (steps.length === 0 || score >= steps[0].score) {
      return 1;
    }

    // последняя ступень, которая СТРОГО выше моего значения. Ступени идут по
    // убыванию, поэтому это правая граница префикса `score > mine`
    let low = 0;
    let high = steps.length - 1;
    let found = -1;

    while (low <= high) {
      const mid = (low + high) >> 1;

      if (steps[mid].score > score) {
        found = mid;
        low = mid + 1;
      } else {
        high = mid - 1;
      }
    }

    if (found === -1) {
      return 1;
    }

    // хвост обрезан, а игрок ниже последней известной ступени — точного
    // ответа лестница не знает
    if (!complete && found === steps.length - 1 && score < steps[found].score) {
      return null;
    }

    return steps[found].atOrAbove + 1;
  }

  // число ранжированных в срезе, или null для непрогретого ключа
  static totalOf(distribution) {
    return distribution ? distribution.total : null;
  }

  // уборка протухших ключей: игра может перестать быть популярной, а Map
  // растёт по числу увиденных (игра, срез)
  sweep(now = this._now()) {
    for (const [key, hit] of this._cache) {
      if (!hit.pending && now - hit.at >= this._ttlMs) {
        this._cache.delete(key);
      }
    }
  }
}
