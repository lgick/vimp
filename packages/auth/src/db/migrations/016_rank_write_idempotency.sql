-- host-migration 7.7: идемпотентность записи результата игры. Хост,
-- поднятый из контрольной точки (миграция хоста, эстафета Worker'ов),
-- повторяет запись, которую предшественник мог уже донести, — с тем же
-- write_seq. Повтор с тем же (игрок, игра, write_seq) не пишется.
-- Комнаты (session_id) в ключе нет: копия, записанная без атрибуции (секрет
-- прошлой эпохи, запись до регистрации комнаты), иначе не совпала бы с
-- повтором. Номера не пересекаются между комнатами и входами сами: движок
-- начинает их со случайной точки 48-битного диапазона.
-- Строки без номера (хосты до этой версии) индексом не охватываются и
-- пишутся как раньше. migrate.js прогоняет все файлы на каждом старте —
-- всё IF NOT EXISTS.
ALTER TABLE rank_events ADD COLUMN IF NOT EXISTS write_seq BIGINT;

CREATE UNIQUE INDEX IF NOT EXISTS rank_events_write_seq_idx
  ON rank_events (user_id, game_id, write_seq)
  WHERE write_seq IS NOT NULL;
