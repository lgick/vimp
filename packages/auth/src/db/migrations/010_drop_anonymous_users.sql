-- Личности dev-логина, у которых вход не дошёл до установки ника (ник был
-- занят другим регистром — см. devLogin). Ни рангов, ни состояний на них нет.
--
-- Только provider='dev' и только старше часа: у OAuth nick IS NULL — это
-- ШТАТНЫЙ шаг между callback'ом и POST /nick, и такая строка принадлежит
-- живому пользователю, стоящему сейчас на экране выбора ника. migrate.js
-- гоняет каталог целиком на каждом деплое (таблицы версий нет), поэтому
-- условие обязано оставаться безопасным при любом повторе
DELETE FROM users
 WHERE nick IS NULL
   AND provider = 'dev'
   AND created_at < now() - interval '1 hour';
