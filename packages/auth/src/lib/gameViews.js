// Проекции строки реестра игр под получателя. Полная форма (mapGame) — одна
// на все запросы, отдающие строку целиком: иначе ответ POST/PATCH расходится
// со списком того же ресурса. Но получателей у неё два, и видят они разное.

/**
 * Строка игры, какой её видит АВТОР (`GET /games/mine`, ответы на его
 * заявки).
 *
 * Модерация со стороны автора анонимна: ему адресовано ЗАМЕЧАНИЕ модератора
 * (`moderatorNote`), а не личность. Персональная адресация отказа — «эту
 * заявку зарубил вот этот человек» — это про травлю модераторов, и вводить
 * её надо осознанно, а не побочным эффектом общей проекции строки. Наружу
 * (`GET /games`) ник модератора не едет по той же причине.
 * @param {Object} game - Полная строка игры (mapGame).
 * @returns {Object} Та же строка без `moderatorNick`.
 */
export function forAuthor({ moderatorNick, ...game }) {
  return game;
}

export default forAuthor;
