// Сервис пула зависимостей `accolades` (snakes-v3 этап 4): отвечает part'у
// на один вопрос — «какое место у этой сущности в глобальном топе?».
//
// Места считает хост (host/meta/modules/Accolades.js) по тому же публичному
// топу, что рисует лобби, и рассылает их порт ACCOLADES_DATA только когда
// они изменились. Движок не знает, что игра нарисует за место: он раздаёт
// числа, а знак — дело part'а.
//
// Ключи приходят строками (gameId на стороне движка — строка), поэтому
// placeOf приводит запрошенный id к строке: у part'а id экземпляра может
// быть числом ключа кадра.
export function createAccolades() {
  let places = {};

  return {
    // применяет рассылку хоста целиком: она всегда полная, а не дельта
    apply(data) {
      places = data || {};
    },

    // { daily, monthly } — всегда объект: незнакомый id (бот, гость,
    // сущность без игрока) не в топе, и это не аварийный случай
    placeOf(id) {
      return places[String(id)] || { daily: null, monthly: null };
    },
  };
}
