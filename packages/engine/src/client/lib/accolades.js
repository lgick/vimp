// Сервис пула зависимостей `accolades` (snakes-v3 этап 4): всё, что комната
// знает о глобальном топе игры.
//
// Отвечает на три вопроса:
//   placeOf(id)        — какое место у этой сущности в топе-10 (для part'а,
//                        который рисует за место знак);
//   boardOf(period)    — сам топ строками (для режима stat 'leaderboard');
//   selfOf(id, period) — место и очки самого игрока, чтобы он видел свою
//                        строку, даже когда в топ не входит.
//
// ЗА ТОПОМ ХОДИТ ХОСТ, А НЕ КЛИЕНТ. Места и таблицу считает
// host/meta/modules/Accolades.js по тому же публичному топу, что рисует
// лобби, и шлёт их портом ACCOLADES_DATA только когда они изменились. Клиент
// в матче не обращается к мастеру вовсе: игрок разговаривает со своим игровым
// сервером. На целевом масштабе (100 игр × 100 серверов × 8 игроков) разница
// между «спрашивает каждый клиент» и «спрашивает комната» — четыре порядка на
// самом дорогом запросе схемы, см. комментарий в хостовом модуле.
//
// Движок не знает, что игра нарисует за место: он раздаёт числа, а знак —
// дело part'а.
//
// Ключи приходят строками (gameId на стороне движка — строка), поэтому
// placeOf/selfOf приводят запрошенный id к строке: у part'а id экземпляра
// может быть числом ключа кадра.
export function createAccolades() {
  let places = {};
  let boards = {};
  let self = {};

  return {
    // применяет рассылку хоста целиком: она всегда полная, а не дельта
    apply(data) {
      places = data?.places || {};
      boards = data?.boards || {};
      self = data?.self || {};
    },

    // { daily, monthly } — всегда объект: незнакомый id (бот, гость,
    // сущность без игрока) не в топе, и это не аварийный случай
    placeOf(id) {
      return places[String(id)] || { daily: null, monthly: null };
    },

    // [{ place, nick, score }] среза ('day'/'month'); пустой массив, пока
    // первая рассылка не пришла — это нормальное состояние, а не сбой
    boardOf(period) {
      return boards[period] || [];
    },

    // { place, score } игрока в срезе или null: место есть только у
    // ранжированного за период участника с проверенной личностью
    selfOf(id, period) {
      return self[String(id)]?.[period] ?? null;
    },
  };
}
