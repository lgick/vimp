// Сервис пула зависимостей `localPlayer`: отвечает part'у на один вопрос —
// «эта сущность моя или чужая?».
//
// Свой gameId знает только клиентское ядро (ClientCore.my_game_id()), а part
// получает id своего экземпляра четвёртым аргументом конструктора
// (GameModel.create → { id }). Свести одно с другим внутри игры было нечем:
// поэтому сервис общий, а не переизобретается каждой игрой заново.
//
// Читает id ЛЕНИВО, на каждый вызов: player-блок приходит только с первым
// бинарным кадром, а сущности создаются раньше — из FIRST_SHOT_DATA. Флаг,
// вычисленный в конструкторе part'а, был бы для своего же персонажа ложным.
//
// getCore — геттер ядра, а не само ядро: ядро создаётся позже пула сервисов и
// пересоздаётся на смене игры.
export function createLocalPlayer(getCore) {
  return {
    // свой gameId или null, пока player-блок не пришёл (ядро отдаёт -1)
    get id() {
      const id = getCore()?.my_game_id?.();

      return typeof id === 'number' && id >= 0 ? id : null;
    },

    // id сущности приходит в part ключом объекта кадра, то есть СТРОКОЙ —
    // сравнение приводит обе стороны к строке, иначе '3' !== 3 и звук своего
    // персонажа не отличить от чужого
    is(id) {
      const my = this.id;

      if (my === null || id === null || id === undefined) {
        return false;
      }

      return String(id) === String(my);
    },
  };
}
