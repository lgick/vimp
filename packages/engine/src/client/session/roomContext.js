// Общее состояние вкладки в комнате (лобби-режим): его читают и меняют
// роли хоста, гостя, беты, промоушен и маршруты (client/session/*).
// Обычный объект, а не класс: модули получают одну и ту же ссылку от
// сборщика (client/main.js), тесты — свежую на каждый сценарий.

/**
 * @returns {{
 *   roomId: string|null,
 *   epoch: number|null,
 *   memberJoined: boolean,
 *   entered: boolean,
 *   startFailed: boolean,
 * }}
 */
export function createRoomContext() {
  return {
    // комната, в которой вкладка гость или хост
    roomId: null,
    // эпоха хоста комнаты, ответившего последним: ответы прежних эпох чужие
    epoch: null,
    // вкладка объявила мастеру членство (join_room) и повторяет его после
    // реконнекта сигналинга — даже если WebRTC в этот момент переподключается
    memberJoined: false,
    // вкладка ушла из лобби в комнату (по ссылке или из лобби). Не
    // сбрасывается: после разрыва страница — остатки матча, и новый маршрут
    // из hashchange поднимается перезагрузкой, а не бутстрапом поверх них
    entered: false,
    // Worker комнаты не поднялся: та же быстрая игра создала бы её снова и
    // снова — поэтому уход на главную, как при кике
    startFailed: false,
  };
}
