// Якорная форма паттерна поля формы — общая для клиента и контракт-чекера.
//
// Браузер применяет атрибут `pattern` ко ВСЕЙ строке, оборачивая паттерн в
// `^(?:…)$` сам. Движок повторяет это за ним (formBuilder.validateField), а
// правило B5 обязано компилировать ровно ту же форму: иначе «компилируется»
// у чекера и у клиента разъедется молча, и правило начнёт обещать то, чего
// не проверяет.

/**
 * @param {string} regExp - Паттерн из дескриптора поля (строка, не RegExp).
 * @returns {RegExp} Скомпилированный паттерн, привязанный ко всей строке.
 * @throws {SyntaxError} Если паттерн не компилируется.
 */
export function anchorPattern(regExp) {
  return new RegExp(`^(?:${regExp})$`);
}
