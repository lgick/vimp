import { createRegistry } from './registry.js';

// Реестр возможностей движка (этап 5 плана plugin-forward-compat). После
// этапов 1-4 плагинная поверхность append-only, и отвергать игру за возраст
// стало не за что: единственная законная причина отказа — игра просит
// возможность, которой в этой сборке движка ещё нет, то есть она НОВЕЕ
// движка. Список запрошенного игра пишет в необязательное поле
// `GameManifest.requires`; манифест без него (все опубликованные до этапа 5)
// значит «ничего сверх базового не нужно».
//
// Реестр append-only (И1): имя, однажды объявленное, поддерживается вечно —
// опубликованная игра могла записать его в `requires`, и её dist больше
// никто не тронет. Вывод из эксплуатации = алиас на новое имя, но не
// удаление строки.
//
// Что сюда попадает: возможность, без которой игра не запустится вовсе, а не
// каждое движковое улучшение. Игре, которая деградирует штатно (не просит
// сервис, не подписана на порт), объявлять ничего не нужно — умолчания
// этапа 2 и словари этапа 3 её и так примут.
export const ENGINE_CAPABILITIES = createRegistry('engine-capabilities', [
  // срезы рейтинга (day/month/all) в лобби и на хосте
  { value: 'stat.leaderboard', since: '0.20.0' },
  // порт ACCOLADES_DATA (18) + сервис пула `accolades`
  { value: 'accolades', since: '0.21.0' },
  // dispatch/abi_describe в ядре (этап 4): опциональные вызовы ядра
  { value: 'dispatch', since: '0.23.0' },
]);

// плоский список имён — то, чем правило контракта B2 проверяет `requires`
export const CAPABILITIES = ENGINE_CAPABILITIES.values();

export default ENGINE_CAPABILITIES;
