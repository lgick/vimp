import { createRegistry } from '../lib/registry.js';

// Реестр опкодов `dispatch` (этап 4 плана plugin-forward-compat). Таблица
// экспортов wasm-ядра заморожена: символ, которого нет в уже опубликованном
// `.wasm`, там не появится никогда, и никакой адаптер его не синтезирует.
// Поэтому КАЖДАЯ будущая возможность ядра приезжает опкодом — строкой,
// которую ядро либо понимает, либо нет, — а не новым методом.
//
// Реестр append-only (И1): опкод, который могла начать понимать игра,
// существует вечно. Удаление опкода = удаление возможности, на которую
// игра уже могла опереться.
//
// Форма записи: `payload`/`response` фиксируют кодировку байтов конкретного
// опкода (сам `dispatch` их не знает — он возит сырые `Uint8Array`).
// Пустой ответ ядра — «опкод не обработан»; `[0x00]` — «обработан, ответа
// нет» (соглашение `abi::dispatch_result` в крейте).
export const abiOps = createRegistry('abiOps', [
  // курированный дамп мира ядра; дублирует замороженный метод debug_json,
  // с которого началась проверка механизма (этап 4.6)
  {
    value: 'debug.json',
    since: 4,
    payload: 'none',
    response: 'json',
  },
]);

// плоский список активных опкодов — то, что вправе позвать движок
export const ABI_OPS = abiOps.values();

export default abiOps;
